# PDLP: Permutation Group Discrete Logarithm — sigma^a = tau in S_n
# ---------------------------------------------------------------------------

class PermutationDLPGenerator(ProblemGenerator):
    """PDLP: Given permutations sigma and tau = sigma^a in S_n, find a.

    sigma is chosen to have large order (a single n-cycle has order n).
    The cyclic group is <sigma> = {sigma^0, sigma^1, ..., sigma^{n-1}}.
    """
    problem_id = "PDLP"
    n_inputs = 0  # variable, set at init

    def __init__(self, p: int, seed: int = 42, n: int = 0):
        super().__init__(p, seed)
        self.n = n if n > 0 else min(p, 127)  # permutation size
        self.n_inputs = self.n * 2  # sigma (n ints) + tau (n ints)
        self._cached_perm = None
        self._cached_order = 0

    def _perm_mul(self, sigma, tau):
        """Compose: (sigma * tau)(i) = sigma[tau[i]]."""
        return [sigma[tau[i]] for i in range(len(sigma))]

    def _perm_pow(self, k, sigma):
        n = len(sigma)
        result = list(range(n))  # identity
        base = list(sigma)
        while k:
            if k & 1:
                result = self._perm_mul(base, result)
            base = self._perm_mul(base, base)
            k >>= 1
        return result

    def _perm_order(self, sigma):
        n = len(sigma)
        result = self._perm_pow(1, sigma)
        order = 1
        identity = list(range(n))
        while result != identity:
            result = self._perm_mul(result, sigma)
            order += 1
            if order > n * n + 1:
                return 0
        return order

    def _find_good_perm(self):
        """Find a permutation with large order (n-cycle has order n)."""
        if self._cached_perm is not None:
            return self._cached_perm, self._cached_order
        n = self.n
        for _ in range(100):
            perm = list(range(n))
            self.rng.shuffle(perm)
            order = self._perm_order(perm)
            if order >= n:
                self._cached_perm = perm
                self._cached_order = order
                return perm, order
        # fallback: a simple n-cycle
        perm = list(range(1, n)) + [0]
        self._cached_perm = perm
        self._cached_order = n
        return perm, n

    def generate_all(self) -> List[ProblemSpec]:
        sigma, order = self._find_good_perm()
        if order < 5:
            return []
        specs = []
        for a in range(1, order):
            tau = self._perm_pow(a, sigma)
            inputs = list(sigma) + list(tau)
            specs.append(ProblemSpec(
                problem_id=self.problem_id,
                prime=self.p,
                inputs=inputs,
                target=a,
                metadata={"sigma": sigma, "tau": tau, "a": a, "order": order, "n": self.n},
            ))
        return specs

    def solution_space_size(self) -> int:
        sigma, order = self._find_good_perm()
        return max(0, order - 1) if sigma else 0

    def verify(self, spec: ProblemSpec) -> bool:
        sigma = spec.metadata["sigma"]
        a = spec.target
        tau = self._perm_pow(a, sigma)
        return tau == spec.metadata["tau"]


