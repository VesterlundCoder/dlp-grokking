def generate_dataset(
    problem: str,
    prime: int,
    train_size: int,
    output_dir: str,
    seed: int = 42,
    perm_n: int = 0,
):
    """Generate and save a dataset to disk for later training."""
    gen_kwargs = {}
    if problem == "PDLP":
        gen_kwargs["n"] = perm_n if perm_n > 0 else min(prime, 127)

    gen = build_generator(problem, prime, seed=seed, **gen_kwargs)
    tokenizer = GrokkingTokenizer(prime)
    n_actual_inputs = gen.n_inputs if gen.n_inputs > 0 else N_INPUTS_MAP.get(problem, 2)
    max_len = compute_max_len(problem, prime, n_actual_inputs)

    space_size = gen.solution_space_size()
    n_train = min(train_size, space_size - 1) if space_size > 0 else train_size
    n_total = min(n_train * 3, space_size) if space_size > 0 else n_train * 3

    print(f"Generating dataset: {problem}, p={prime}", flush=True)
    print(f"  space_size={space_size}, n_train={n_train}, n_total~={n_total}", flush=True)

    specs = gen.generate(n_total) if n_total < space_size else gen.generate_all()
    train_specs, test_specs = split_specs(specs, n_train, seed=seed)

    train_ds = GrokkingDataset(train_specs, tokenizer, max_len)
    test_ds = GrokkingDataset(test_specs, tokenizer, max_len)

    os.makedirs(output_dir, exist_ok=True)
    dataset_path = os.path.join(output_dir, f"{problem}_p{prime}_train{n_train}.pt")
    torch.save({
        "train": [(t, tgt) for t, tgt in train_ds.examples],
        "test": [(t, tgt) for t, tgt in test_ds.examples],
        "metadata": {
            "problem": problem,
            "prime": prime,
            "space_size": space_size,
            "n_train": len(train_specs),
            "n_test": len(test_specs),
            "max_len": max_len,
            "vocab_size": tokenizer.vocab_size,
            "seed": seed,
        },
    }, dataset_path)

    print(f"Saved dataset: {dataset_path}", flush=True)
    print(f"  Train: {len(train_ds)}, Test: {len(test_ds)}, Vocab: {tokenizer.vocab_size}, Max len: {max_len}", flush=True)
    return dataset_path


