class PhaseClassifier:
    """Classify training phase based on train/test accuracy."""
    def __init__(self):
        self.history = []

    def classify(self, train_acc: float, test_acc: float, epoch: int) -> str:
        if math.isnan(train_acc):
            return "unknown"
        if train_acc < 0.5:
            return "warmup"
        if test_acc > 0.9:
            return "grokked"
        if train_acc > 0.99 and test_acc < 0.1:
            return "memorization"
        if train_acc > 0.99 and test_acc > 0.1:
            return "transition"
        return "learning"

    def update(self, train_acc: float, test_acc: float, epoch: int) -> str:
        phase = self.classify(train_acc, test_acc, epoch)
        self.history.append((epoch, phase, train_acc, test_acc))
        return phase

    def get_summary(self) -> Dict:
        if not self.history:
            return {}
        grokking_onset = None
        grokking_completion = None
        for epoch, phase, train_acc, test_acc in self.history:
            if phase == "transition" and grokking_onset is None:
                grokking_onset = epoch
            if phase == "grokked" and grokking_completion is None:
                grokking_completion = epoch
        return {
            "grokking_onset": grokking_onset,
            "grokking_completion": grokking_completion,
            "final_phase": self.history[-1][1],
        }


def compute_accuracy(model, dataset, tokenizer, device, batch_size=512):
    """Compute accuracy on a dataset."""
    model.eval()
    correct = 0
    total = 0
    loss_sum = 0.0
    with torch.no_grad():
        for i in range(0, len(dataset), batch_size):
            batch_tokens = []
            batch_targets = []
            for j in range(i, min(i + batch_size, len(dataset))):
                t, tgt = dataset.examples[j]
                batch_tokens.append(t)
                batch_targets.append(tgt)
            tokens = torch.stack(batch_tokens).to(device)
            targets = torch.tensor(batch_targets, dtype=torch.long).to(device)
            logits = model(tokens)
            if logits.dim() == 3:
                seq_lens = (tokens != tokenizer.pad_id).sum(dim=1) - 1
                idx_pos = seq_lens.unsqueeze(-1).unsqueeze(-1).expand(-1, 1, logits.size(-1))
                logits_at_pos = logits.gather(1, idx_pos).squeeze(1)
            else:
                logits_at_pos = logits
            preds = logits_at_pos.argmax(dim=-1)
            correct += (preds == targets).sum().item()
            total += len(targets)
            loss_sum += F.cross_entropy(logits_at_pos, targets).item() * len(targets)
    model.train()
    acc = correct / total if total > 0 else 0.0
    avg_loss = loss_sum / total if total > 0 else 0.0
    return acc, avg_loss


def train_cyclic_dlp(
    problem: str,
    prime: int,
    d_model: int = 512,
    n_layers: int = 8,
    n_heads: int = 16,
    epochs: int = 200_000,
    lr: float = 1e-3,
    wd_start: float = 0.05,
    wd_max: float = 0.30,
    wd_step: float = 0.05,
    wd_acc_threshold: float = 0.05,
    train_size: int = 150_000,
    train_frac: float = 0.3,
    seed: int = 42,
    output_dir: str = "results/lumi",
    checkpoint_interval: int = 1000,
    eval_interval: int = 10,
    early_stop_patience: int = 100,
    early_stop_threshold: float = 0.99,
    use_amp: bool = True,
    log_wandb: bool = False,
    ddp: bool = False,
    perm_n: int = 0,
):
    """Train a cyclic DLP solver with progressive weight decay."""

    # Setup DDP
    local_rank = 0
    world_size = 1
    if ddp:
        local_rank = int(os.environ.get("LOCAL_RANK", 0))
        world_size = int(os.environ.get("WORLD_SIZE", 1))
        torch.distributed.init_process_group(backend="nccl")
        torch.cuda.set_device(local_rank)

    # Device
    if torch.cuda.is_available():
        device = torch.device(f"cuda:{local_rank}" if ddp else "cuda")
    elif torch.backends.mps.is_available():
        device = torch.device("mps")
    else:
        device = torch.device("cpu")

    if local_rank == 0:
        print(f"Device: {device}", flush=True)

    # Generate dataset
    gen_kwargs = {}
    if problem == "PDLP":
        gen_kwargs["n"] = perm_n if perm_n > 0 else min(prime, 127)

    gen = build_generator(problem, prime, seed=seed, **gen_kwargs)
    tokenizer = GrokkingTokenizer(prime)

    n_actual_inputs = gen.n_inputs if gen.n_inputs > 0 else N_INPUTS_MAP.get(problem, 2)
    max_len = compute_max_len(problem, prime, n_actual_inputs)

    space_size = gen.solution_space_size()
    if local_rank == 0:
        print(f"Problem: {problem}, prime={prime}, space_size={space_size}", flush=True)
        print(f"n_inputs={n_actual_inputs}, max_len={max_len}, vocab_size={tokenizer.vocab_size}", flush=True)

    # Determine train/test sizes
    n_train = min(train_size, space_size - 1) if space_size > 0 else train_size
    n_total = min(n_train * 3 if train_frac == 0.3 else int(n_train / train_frac), space_size) if space_size > 0 else n_train * 3

    if local_rank == 0:
        print(f"Generating dataset: n_train={n_train}, n_total~={n_total}...", flush=True)

    specs = gen.generate(n_total) if n_total < space_size else gen.generate_all()
    train_specs, test_specs = split_specs(specs, n_train, seed=seed)

    train_ds = GrokkingDataset(train_specs, tokenizer, max_len)
    test_ds = GrokkingDataset(test_specs, tokenizer, max_len)

    if local_rank == 0:
        print(f"Train: {len(train_ds)}, Test: {len(test_ds)}", flush=True)

    # Build model
    model = GrokkingTransformer(
        vocab_size=tokenizer.vocab_size,
        d_model=d_model,
        n_heads=n_heads,
        n_layers=n_layers,
        max_len=max_len,
    ).to(device)

    if ddp:
        model = nn.parallel.DistributedDataParallel(
            model, device_ids=[local_rank], output_device=local_rank
        )

    n_params = model.count_parameters() if hasattr(model, 'count_parameters') else sum(p.numel() for p in model.parameters())
    if local_rank == 0:
        print(f"Model: {n_params:,} params, d={d_model}, L={n_layers}, H={n_heads}", flush=True)

    # Optimizer — start with low WD, ramp up
    current_wd = wd_start
    optimizer = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=current_wd)
    last_wd_acc_level = 0

    # AMP scaler
    scaler = torch.amp.GradScaler('cuda') if use_amp and device.type == "cuda" else None
    amp_dtype = torch.float16 if device.type == "cuda" else None

    # Output directory
    if local_rank == 0:
        os.makedirs(output_dir, exist_ok=True)
        os.makedirs(os.path.join(output_dir, "checkpoints"), exist_ok=True)

        # Save config
        config = {
            "problem": problem, "prime": prime, "d_model": d_model,
            "n_layers": n_layers, "n_heads": n_heads, "n_params": n_params,
            "epochs": epochs, "lr": lr,
            "wd_schedule": {"start": wd_start, "max": wd_max, "step": wd_step, "acc_threshold": wd_acc_threshold},
            "train_size": len(train_ds), "test_size": len(test_ds),
            "seed": seed, "device": str(device),
            "checkpoint_interval": checkpoint_interval,
            "early_stop_patience": early_stop_patience,
            "early_stop_threshold": early_stop_threshold,
            "use_amp": use_amp, "ddp": ddp, "world_size": world_size,
            "vocab_size": tokenizer.vocab_size, "max_len": max_len,
            "space_size": space_size,
        }
        with open(os.path.join(output_dir, "config.json"), "w") as f:
            json.dump(config, f, indent=2)

    # Prepare tensors (full-batch)
    train_tokens = torch.stack([train_ds.examples[i][0] for i in range(len(train_ds))]).to(device)
    train_targets = torch.tensor([train_ds.examples[i][1] for i in range(len(train_ds))], dtype=torch.long).to(device)

    # Metrics file
    metrics_path = os.path.join(output_dir, "metrics.jsonl") if local_rank == 0 else None
    phase_clf = PhaseClassifier()

    # Training loop
    start_time = time.time()
    consecutive_high = 0
    best_test_acc = 0.0
    early_stopped = False
    full_batch_size = len(train_ds)  # full-batch per GPU

    if local_rank == 0:
        print(f"\nStarting training: {epochs} epochs, batch_size={full_batch_size}", flush=True)
        print(f"WD schedule: start={wd_start}, max={wd_max}, step={wd_step}, threshold={wd_acc_threshold}", flush=True)
        print(f"AMP: {use_amp and device.type == 'cuda'}, DDP: {ddp} (world_size={world_size})", flush=True)
        if ddp:
            print(f"DDP: each GPU processes {full_batch_size // world_size} samples/epoch (strided)", flush=True)
        print("", flush=True)

    for epoch in range(epochs):
        model.train()
        perm = torch.randperm(len(train_ds), device=device)
        epoch_loss = 0.0
        n_batches = 0

        # DDP: strided partition — each GPU processes every world_size-th sample
        if ddp:
            gpu_indices = perm[local_rank::world_size]
        else:
            gpu_indices = perm

        for i in range(0, len(gpu_indices), full_batch_size):
            idx = gpu_indices[i:i + full_batch_size]
            xb = train_tokens[idx]
            yb = train_targets[idx]

            if use_amp and device.type == "cuda":
                with torch.amp.autocast('cuda', dtype=amp_dtype):
                    logits = model(xb)
                    if logits.dim() == 3:
                        seq_lens = (xb != tokenizer.pad_id).sum(dim=1) - 1
                        idx_pos = seq_lens.unsqueeze(-1).unsqueeze(-1).expand(-1, 1, logits.size(-1))
                        logits_at_pos = logits.gather(1, idx_pos).squeeze(1)
                    else:
                        logits_at_pos = logits
                    loss = F.cross_entropy(logits_at_pos, yb)

                optimizer.zero_grad()
                scaler.scale(loss).backward()
                scaler.unscale_(optimizer)
                torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
                scaler.step(optimizer)
                scaler.update()
            else:
                logits = model(xb)
                if logits.dim() == 3:
                    seq_lens = (xb != tokenizer.pad_id).sum(dim=1) - 1
                    idx_pos = seq_lens.unsqueeze(-1).unsqueeze(-1).expand(-1, 1, logits.size(-1))
                    logits_at_pos = logits.gather(1, idx_pos).squeeze(1)
                else:
                    logits_at_pos = logits
                loss = F.cross_entropy(logits_at_pos, yb)

                optimizer.zero_grad()
                loss.backward()
                torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
                optimizer.step()

            epoch_loss += loss.item()
            n_batches += 1

        avg_train_loss = epoch_loss / n_batches

        # Evaluate (only on rank 0 when DDP to avoid redundant eval)
        if epoch % eval_interval == 0 or epoch == epochs - 1:
            if ddp and local_rank != 0:
                train_acc = float("nan")
                test_acc = float("nan")
                test_loss = avg_train_loss
            else:
                train_acc, _ = compute_accuracy(model, train_ds, tokenizer, device, batch_size=512)
                test_acc, test_loss = compute_accuracy(model, test_ds, tokenizer, device, batch_size=512)

            # Progressive weight decay ramp
            if not math.isnan(train_acc):
                acc_level = int(train_acc / wd_acc_threshold)
                if acc_level > last_wd_acc_level and current_wd < wd_max:
                    new_wd = min(current_wd + wd_step, wd_max)
                    for pg in optimizer.param_groups:
                        pg['weight_decay'] = new_wd
                    if local_rank == 0:
                        print(f"  WD ramp: {current_wd:.3f} -> {new_wd:.3f} (train_acc={train_acc:.4f}, level={acc_level})", flush=True)
                    current_wd = new_wd
                    last_wd_acc_level = acc_level
        else:
            train_acc = float("nan")
            test_acc = float("nan")
            test_loss = avg_train_loss

        # DDP barrier: ensure all GPUs sync after eval (rank 0 may have taken longer)
        if ddp and (epoch % eval_interval == 0 or epoch == epochs - 1):
            torch.distributed.barrier()

        # Track best
        if not math.isnan(test_acc):
            if test_acc > best_test_acc:
                best_test_acc = test_acc

        # Phase classification
        phase = phase_clf.update(train_acc if not math.isnan(train_acc) else 0.0,
                                 test_acc if not math.isnan(test_acc) else 0.0, epoch)
        is_transition = (phase == "grokked" and
                         len(phase_clf.history) >= 2 and
                         phase_clf.history[-2][1] != "grokked")

        # Log metrics
        if local_rank == 0 and metrics_path:
            elapsed = time.time() - start_time
            metrics = {
                "epoch": epoch,
                "train_acc": train_acc if not math.isnan(train_acc) else None,
                "test_acc": test_acc if not math.isnan(test_acc) else None,
                "train_loss": avg_train_loss,
                "test_loss": test_loss if not math.isnan(test_loss) else None,
                "weight_decay": current_wd,
                "phase": phase,
                "elapsed_s": elapsed,
                "best_test_acc": best_test_acc,
            }
            with open(metrics_path, "a") as f:
                f.write(json.dumps(metrics) + "\n")

        # Checkpoint
        if local_rank == 0 and (epoch + 1) % checkpoint_interval == 0:
            ckpt_path = os.path.join(output_dir, "checkpoints", f"epoch_{epoch:06d}.pt")
            torch.save({
                "epoch": epoch,
                "model_state_dict": (model.module if ddp else model).state_dict(),
                "optimizer_state_dict": optimizer.state_dict(),
                "current_wd": current_wd,
                "best_test_acc": best_test_acc,
            }, ckpt_path)

        # Progress log
        if local_rank == 0 and (epoch % 100 == 0 or epoch == epochs - 1 or (test_acc > 0.1 and epoch % eval_interval == 0)):
            elapsed = time.time() - start_time
            print(f"  Epoch {epoch}/{epochs} | train={train_acc:.4f} test={test_acc:.4f} "
                  f"loss={avg_train_loss:.4f} wd={current_wd:.3f} phase={phase} t={elapsed:.1f}s", flush=True)

        # Early stopping
        if not math.isnan(test_acc) and test_acc > early_stop_threshold:
            consecutive_high += 1
            if consecutive_high >= early_stop_patience:
                if local_rank == 0:
                    print(f"\nEarly stopped at epoch {epoch} (test_acc > {early_stop_threshold} for {consecutive_high} evals)", flush=True)
                early_stopped = True
        else:
            consecutive_high = 0

        if early_stopped:
            break

    # Final checkpoint
    if local_rank == 0:
        final_path = os.path.join(output_dir, "checkpoints", "final.pt")
        torch.save({
            "epoch": epoch,
            "model_state_dict": (model.module if ddp else model).state_dict(),
            "optimizer_state_dict": optimizer.state_dict(),
            "current_wd": current_wd,
            "best_test_acc": best_test_acc,
        }, final_path)

        # Summary
        summary = phase_clf.get_summary()
        summary["best_test_acc"] = best_test_acc
        summary["total_epochs"] = epoch + 1
        summary["final_wd"] = current_wd
        summary["n_params"] = n_params
        with open(os.path.join(output_dir, "summary.json"), "w") as f:
            json.dump(summary, f, indent=2)

        elapsed = time.time() - start_time
        print(f"\nTraining complete: {epoch + 1} epochs in {elapsed:.1f}s", flush=True)
        print(f"Best test acc: {best_test_acc:.4f}", flush=True)
        print(f"Final WD: {current_wd:.3f}", flush=True)
        print(f"Summary: {json.dumps(summary, indent=2)}", flush=True)

    if ddp:
        torch.distributed.destroy_process_group()


