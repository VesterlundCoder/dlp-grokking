# MDLP: Matrix Group Discrete Logarithm — M^a = N in GL(2, F_p)
# ---------------------------------------------------------------------------

class MatrixDLPGenerator(ProblemGenerator):
    """MDLP: Given 2x2 matrices M and N = M^a over F_p, find a.

    Uses F_{p²} arithmetic: a primitive element α = c+di in F_{p²} = F_p[i]
    (where i² = -1) maps to matrix M = [[c, -d], [d, c]] with order p²-1.
    This gives a cyclic subgroup of order p²-1 in GL(2, F_p).
    """
    problem_id = "MDLP"
    n_inputs = 8

    def __init__(self, p: int, seed: int = 42):
        super().__init__(p, seed)
        self._cached_M = None
        self._cached_order = 0

    def _mat_mul(self, A, B):
        a, b, c, d = A
        e, f, g, h = B
        return (
            (a * e + b * g) % self.p,
            (a * f + b * h) % self.p,
            (c * e + d * g) % self.p,
            (c * f + d * h) % self.p,
        )

    def _mat_pow(self, k, M):
        result = (1, 0, 0, 1)
        base = M
        while k:
            if k & 1:
                result = self._mat_mul(result, base)
            base = self._mat_mul(base, base)
            k >>= 1
        return result

    def _fp2_mul(self, x, y):
        """Multiply two elements of F_{p²} represented as (real, imag) with i²=-1."""
        a, b = x
        c, d = y
        return ((a * c - b * d) % self.p, (a * d + b * c) % self.p)

    def _fp2_pow(self, k, x):
        result = (1, 0)
        base = x
        while k:
            if k & 1:
                result = self._fp2_mul(result, base)
            base = self._fp2_mul(base, base)
            k >>= 1
        return result

    def _find_primitive_element_fp2(self):
        """Find a primitive element of F_{p²}* of order p²-1.

        F_{p²} = F_p[i] where i² = -1 (requires p ≡ 3 mod 4 so x²+1 irreducible).
        For p ≡ 1 mod 4, use a different irreducible polynomial.
        """
        if self.p % 4 == 3:
            # x²+1 is irreducible, F_{p²} = F_p[i], i²=-1
            n = self.p * self.p - 1
            factors = set(_prime_factors(n))
            for _ in range(2000):
                c = self.rng.randint(1, self.p - 1)
                d = self.rng.randint(1, self.p - 1)
                alpha = (c, d)
                is_primitive = True
                for q in factors:
                    if self._fp2_pow(n // q, alpha) == (1, 0):
                        is_primitive = False
                        break
                if is_primitive:
                    # Matrix representation: M = [[c, (-d)%p], [d, c]]
                    M = (c, (-d) % self.p, d, c)
                    return M, n
            return None, 0
        else:
            # p ≡ 1 mod 4: find irreducible quadratic x² - t
            for t in range(2, self.p):
                # Check if t is a QR mod p
                if pow(t, (self.p - 1) // 2, self.p) == 1:
                    continue
                # x² - t is irreducible, F_{p²} = F_p[√t]
                n = self.p * self.p - 1
                factors = set(_prime_factors(n))
                for _ in range(2000):
                    c = self.rng.randint(1, self.p - 1)
                    d = self.rng.randint(1, self.p - 1)
                    # (c + d√t)^k in F_{p²}
                    # multiplication: (a+b√t)(c+d√t) = (ac+bdt) + (ad+bc)√t
                    def fp2_mul_t(x, y):
                        a, b = x
                        cc, dd = y
                        return ((a * cc + b * dd * t) % self.p, (a * dd + b * cc) % self.p)
                    def fp2_pow_t(k, x):
                        result = (1, 0)
                        base = x
                        while k:
                            if k & 1:
                                result = fp2_mul_t(result, base)
                            base = fp2_mul_t(base, base)
                            k >>= 1
                        return result
                    alpha = (c, d)
                    is_primitive = True
                    for q in factors:
                        if fp2_pow_t(n // q, alpha) == (1, 0):
                            is_primitive = False
                            break
                    if is_primitive:
                        M = (c, (d * t) % self.p, d, c)
                        return M, n
            return None, 0

    def _find_good_matrix(self):
        if self._cached_M is not None:
            return self._cached_M, self._cached_order
        M, order = self._find_primitive_element_fp2()
        self._cached_M = M
        self._cached_order = order
        return M, order

    def generate(self, n: int) -> List[ProblemSpec]:
        M, order = self._find_good_matrix()
        if M is None or order < 5:
            return []
        if n >= order - 1:
            return self.generate_all()
        specs = []
        seen = set()
        max_attempts = n * 10
        attempts = 0
        while len(specs) < n and attempts < max_attempts:
            a = self.rng.randint(1, order - 1)
            if a not in seen:
                seen.add(a)
                N = self._mat_pow(a, M)
                specs.append(ProblemSpec(
                    problem_id=self.problem_id,
                    prime=self.p,
                    inputs=[M[0], M[1], M[2], M[3], N[0], N[1], N[2], N[3]],
                    target=a,
                    metadata={"M": M, "N": N, "a": a, "order": order},
                ))
            attempts += 1
        return specs

    def generate_all(self) -> List[ProblemSpec]:
        M, order = self._find_good_matrix()
        if M is None or order < 5:
            return []
        specs = []
        for a in range(1, min(order, 500001)):
            N = self._mat_pow(a, M)
            specs.append(ProblemSpec(
                problem_id=self.problem_id,
                prime=self.p,
                inputs=[M[0], M[1], M[2], M[3], N[0], N[1], N[2], N[3]],
                target=a,
                metadata={"M": M, "N": N, "a": a, "order": order},
            ))
        return specs

    def solution_space_size(self) -> int:
        M, order = self._find_good_matrix()
        return max(0, order - 1) if M else 0

    def verify(self, spec: ProblemSpec) -> bool:
        M = spec.metadata["M"]
        a = spec.target
        N = self._mat_pow(a, M)
        return N == spec.metadata["N"]


